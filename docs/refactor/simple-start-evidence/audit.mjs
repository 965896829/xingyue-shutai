import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import * as asar from '@electron/asar';
const base = '.test-output/newbook-20261011';
const source = JSON.parse(fs.readFileSync(path.join(base, 'source-audit.json'), 'utf8'));
const changedUI = source.ui.filter(row => !row.elementsAndLabelsUnchanged).map(row => row.file.replaceAll('\\', '/')).sort();
assert.deepEqual(changedUI, ['src/ui/App.tsx', 'src/ui/TagWorkspace.tsx']);
assert.ok(source.assets.every(row => row.unchanged));
assert.ok(source.comments.every(row => row.added === 0));
assert.deepEqual(source.architecture, []);
assert.deepEqual(source.package.piFiles, []);
assert.deepEqual(source.package.testSecrets, []);
assert.ok(source.package.bundles.every(row => row.matches));
const beforeLock = JSON.parse(fs.readFileSync(path.join(base, 'package-lock.json'), 'utf8'));
const lock = JSON.parse(fs.readFileSync('package-lock.json', 'utf8'));
lock.version = beforeLock.version;
lock.packages[''].version = beforeLock.packages[''].version;
assert.deepEqual(lock, beforeLock);
const digest = value => crypto.createHash('sha256').update(value).digest('hex');
const walk = dir => fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? walk(path.join(dir, entry.name)) : [path.join(dir, entry.name)]);
const archive = 'release/simple-start/win-unpacked/resources/app.asar';
const renderer = walk('dist').map(file => {
  const matches = digest(fs.readFileSync(file)) === digest(asar.extractFile(archive, path.normalize(file)));
  assert.equal(matches, true, file);
  return { file, matches };
});
const skill = walk('resources/skill').map(file => {
  const relative = path.relative('resources/skill', file);
  const packaged = path.join('release/simple-start/win-unpacked/resources/skill', relative);
  assert.equal(digest(fs.readFileSync(file)), digest(fs.readFileSync(packaged)), file);
  return relative;
});
const installer = 'release/simple-start/星月书台 Setup 0.4.5.exe';
const result = { at: new Date().toISOString(), version: source.package.version, changedUI, unchangedUI: source.ui.length - changedUI.length, unchangedAssets: source.assets.length, sourceCommentsAdded: 0, dependenciesUnchanged: true, renderer, skillFilesMatched: skill.length, bundles: source.package.bundles, installer: { path: installer, bytes: fs.statSync(installer).size, sha256: digest(fs.readFileSync(installer)) } };
assert.equal(result.version, '0.4.5');
fs.writeFileSync(path.join(base, 'delivery-report.json'), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));
